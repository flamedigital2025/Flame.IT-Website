export function getSEO(path) {
    if (!path) return seoData['/'];
    // Exact match
    if (seoData[path]) return seoData[path];
    // Check trimmed trailing slash
    const cleanPath = path !== '/' && path.endsWith('/') ? path.slice(0, -1) : path;
    if (seoData[cleanPath]) return seoData[cleanPath];
    // Prefix fallback
    if (cleanPath.startsWith('/services')) return seoData['/services'];
    return seoData['/'];
}

